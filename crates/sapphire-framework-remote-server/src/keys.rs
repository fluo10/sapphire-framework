    #[test]
    fn load_fills_in_a_hand_written_entry_and_writes_it_back() {
        let tmp = tempfile::tempdir().unwrap();
        let p = path(&tmp);
        std::fs::write(
            &p,
            "[[key]]\ntoken = \"sjt_hand\"\nlabel = \"typed by hand\"\n",
        )
        .unwrap();

        let store = KeyStore::load(&p).unwrap();

        assert_eq!(store.entries().len(), 1);
        let id = store.entries()[0].id;
        assert_ne!(id, Uuid::nil(), "補完された id は nil であってはならない");
        assert_eq!(
            id.to_string().parse::<Uuid>().unwrap(),
            id,
            "表示形から読み戻せる"
        );
        assert_eq!(store.entries()[0].label.as_deref(), Some("typed by hand"));

        // 補完がファイルへ書き戻されていること
        let reloaded = KeyStore::load(&p).unwrap();
        assert_eq!(reloaded.entries()[0].id, store.entries()[0].id);
        assert_eq!(
            reloaded.entries()[0].created_at,
            store.entries()[0].created_at
        );
    }

    #[test]
    fn load_rejects_two_keys_that_share_an_id() {
        // 手で書くことはまず無いが、エントリごとコピーして複製する事故はある。
        // 重複したまま読むと revoke がどちらの鍵か決められない。
        let tmp = tempfile::tempdir().unwrap();
        let p = path(&tmp);
        std::fs::write(
            &p,
            "[[key]]\ntoken = \"sjt_a\"\nid = \"6f1c4a9e-5d2b-4c8f-9a30-1e7b5c8d2f41\"\n\n\
             [[key]]\ntoken = \"sjt_b\"\nid = \"6f1c4a9e-5d2b-4c8f-9a30-1e7b5c8d2f41\"\n",
        )
        .unwrap();

        let err = match KeyStore::load(&p) {
            Ok(_) => panic!("重複した id を受け入れてはならない"),
            Err(e) => e.to_string(),
        };

        assert!(
            err.contains("6f1c4a9e-5d2b-4c8f-9a30-1e7b5c8d2f41"),
            "どの id が重複したか示す: {err}"
        );
    }

