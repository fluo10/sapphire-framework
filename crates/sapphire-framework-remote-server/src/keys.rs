    #[test]
    fn a_failed_save_leaves_the_existing_key_file_intact() {
        // 鍵ファイルは資格情報の唯一の保管場所で、`load` が補完を書き戻すたび
        // ——つまりごく普通の起動のたびに——書き直される。その場で truncate して
        // いると、書き込みが途中で失敗した瞬間に全トークンが消える。
        // 一時ファイル経由なら、失敗しても本体は前の内容のまま残る。
        let tmp = tempfile::tempdir().unwrap();
        let p = path(&tmp);
        let mut store = KeyStore::load(&p).unwrap();
        let keeper = store
            .generate("sjt", None, Some("keeper".into()), None)
            .unwrap();
        let before = std::fs::read_to_string(&p).unwrap();

        // 一時ファイルの置き場所をディレクトリで塞ぐ → 一時ファイルを作れない。
        // 本体を直接 truncate する実装なら、ここは素通りして上書きしてしまう。
        std::fs::create_dir(tmp.path().join("keys.toml.tmp")).unwrap();

        assert!(
            store
                .generate("sjt", None, Some("doomed".into()), None)
                .is_err(),
            "一時ファイルを作れないなら保存は失敗しなければならない"
        );
        assert_eq!(
            std::fs::read_to_string(&p).unwrap(),
            before,
            "失敗した保存が本体を書き換えてはならない"
        );
        let reloaded = KeyStore::load(&p).unwrap();
        assert_eq!(reloaded.entries().len(), 1);
        assert_eq!(reloaded.entries()[0].id, keeper.id);
    }

